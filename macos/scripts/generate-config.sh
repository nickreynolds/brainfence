#!/bin/bash
# Generates Brainfence/Generated/Secrets.generated.swift from the repo-root .env
# (the same file the Android build reads). Environment variables of the same
# name take precedence, for CI.
#
# Only client-safe values are embedded: the Supabase URL, the *publishable*
# key and the PowerSync URL. Never add SUPABASE_SECRET_KEY here.
set -euo pipefail

MACOS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="${MACOS_DIR}/../.env"
OUT_DIR="${MACOS_DIR}/Brainfence/Generated"
OUT="${OUT_DIR}/Secrets.generated.swift"

read_var() {
    local key="$1"
    if [[ -n "${!key:-}" ]]; then
        printf '%s' "${!key}"
        return
    fi
    [[ -f "$ENV_FILE" ]] || return 0
    grep -E "^[[:space:]]*${key}=" "$ENV_FILE" | tail -1 | cut -d= -f2- \
        | sed -e 's/^[[:space:]]*//' -e 's/[[:space:]]*$//' -e 's/^"\(.*\)"$/\1/' -e "s/^'\(.*\)'$/\1/"
}

swift_escape() {
    printf '%s' "$1" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g'
}

SUPABASE_URL="$(read_var SUPABASE_URL)"
SUPABASE_PUBLISHABLE_KEY="$(read_var SUPABASE_PUBLISHABLE_KEY)"
POWERSYNC_URL="$(read_var POWERSYNC_URL)"

missing=()
[[ -n "$SUPABASE_URL" ]] || missing+=(SUPABASE_URL)
[[ -n "$SUPABASE_PUBLISHABLE_KEY" ]] || missing+=(SUPABASE_PUBLISHABLE_KEY)
[[ -n "$POWERSYNC_URL" ]] || missing+=(POWERSYNC_URL)
if (( ${#missing[@]} )); then
    echo "error: missing ${missing[*]} — set them in ${ENV_FILE} (see .env.example)" >&2
    exit 1
fi

mkdir -p "$OUT_DIR"
TMP="$(mktemp)"
cat > "$TMP" <<EOF
// Generated by scripts/generate-config.sh from ../.env — do not edit or commit.

enum Secrets {
    static let supabaseURL = "$(swift_escape "$SUPABASE_URL")"
    static let supabasePublishableKey = "$(swift_escape "$SUPABASE_PUBLISHABLE_KEY")"
    static let powerSyncURL = "$(swift_escape "$POWERSYNC_URL")"
}
EOF

# Only touch the output when it changes, so incremental builds stay incremental.
if ! cmp -s "$TMP" "$OUT" 2>/dev/null; then
    mv "$TMP" "$OUT"
else
    rm -f "$TMP"
fi
