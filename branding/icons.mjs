// Builds every client's app icon, and the Play Store graphics, from the
// approved mark (round 1 Chainlink Crown, Static). Run with `npm run icons`
// and commit the results; don't edit the generated images by hand.
//
//   Android  android/app/src/main/res/mipmap-*/ic_launcher_{foreground,monochrome}.png
//            and values/ic_launcher_background.xml (adaptive icon layers)
//   Windows  desktop-app/resources/icon.ico, icon.png, tray.png, tray@2x.png
//   macOS    macos/Brainfence/Resources/Assets.xcassets/AppIcon.appiconset
//   Play     store/play/icon-512.png, feature-graphic.png
//   Website  site/icon.svg, site/apple-touch-icon.png

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { Resvg } from '@resvg/resvg-js';

import { S, createCtx, doc } from './src/fx.mjs';
import { palettes } from './src/palettes.mjs';
import { markBody, renderFeatureGraphic, renderMark } from './src/compose.mjs';
import mark from './src/marks/chainlink-crown.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const p = palettes.find((x) => x.id === 'static');

let count = 0;
const write = (rel, data) => {
  const file = join(root, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, data);
  count++;
};
const png = (svg, size) => Buffer.from(new Resvg(svg, { fitTo: { mode: 'width', value: size } }).render().asPng());

// The figure (head, visor and crown) spans about 260–770 × 180–910 of the
// 1024 tile, centered on (512, 545); 375 reaches its farthest corner.
const FIGURE = { cx: 512, cy: 545, r: 375 };

// The mark as drawn, or (k ≠ 1) scaled by k about the figure's center and
// recentered on the canvas. shape clips the result to an outline.
function svg(variant, { k = 1, background = true, back = true, shape = '' } = {}) {
  const ctx = createCtx('i');
  const body = markBody(mark, p, variant, ctx, { background: false, back });
  const fill = background ? `<rect width="${S}" height="${S}" fill="${p.bg}"/>` : '';
  const figure =
    k === 1 ? body : `<g transform="translate(${S / 2 - FIGURE.cx * k} ${S / 2 - FIGURE.cy * k}) scale(${k})">${body}</g>`;
  if (!shape) return doc(fill + figure, ctx);
  const clip = ctx.uid('clip');
  ctx.def(`<clipPath id="${clip}">${shape}</clipPath>`);
  return doc(`<g clip-path="url(#${clip})">${fill}${figure}</g>`, ctx);
}

// Android adaptive icon: 108dp layers, of which launchers show the middle
// 72dp and guarantee a 66dp circle. Fit the figure inside that circle.
const SAFE = (33 / 108) * S;
const adaptive = { k: SAFE / FIGURE.r, background: false };
const DENSITIES = { mdpi: 1, hdpi: 1.5, xhdpi: 2, xxhdpi: 3, xxxhdpi: 4 };
const res = 'android/app/src/main/res';
for (const [d, scale] of Object.entries(DENSITIES)) {
  write(`${res}/mipmap-${d}/ic_launcher_foreground.png`, png(svg('icon', adaptive), 108 * scale));
  write(`${res}/mipmap-${d}/ic_launcher_monochrome.png`, png(svg('mono', { ...adaptive, back: false }), 108 * scale));
}
write(
  `${res}/values/ic_launcher_background.xml`,
  `<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by branding/icons.mjs. -->\n<resources>\n    <color name="ic_launcher_background">${p.bg}</color>\n</resources>\n`,
);

// Windows: a rounded tile. Below 48px the rings turn to noise, so small sizes
// drop them and enlarge the figure.
const tile = `<rect width="${S}" height="${S}" rx="${S * 0.2}"/>`;
const windows = (size) => png(size < 48 ? svg('icon', { k: 1.25, back: false, shape: tile }) : svg('icon', { shape: tile }), size);
write('desktop-app/resources/icon.ico', ico([16, 24, 32, 48, 64, 128, 256].map((s) => windows(s))));
write('desktop-app/resources/icon.png', windows(512));
// Tray: the figure alone, as large as fits.
const tray = svg('icon', { k: (S * 0.48) / FIGURE.r, background: false, back: false });
write('desktop-app/resources/tray.png', png(tray, 16));
write('desktop-app/resources/tray@2x.png', png(tray, 32));

// macOS: Apple's icon grid puts an 824px rounded square, with a soft shadow,
// on the 1024px canvas.
const mac = (() => {
  const inner = svg('icon').replace(/^<svg[^>]*>/, '').replace(/<\/svg>\n$/, '');
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S} ${S}" width="${S}" height="${S}">` +
    `<defs><clipPath id="sq"><rect x="100" y="100" width="824" height="824" rx="185"/></clipPath>` +
    `<filter id="sh" x="-10%" y="-10%" width="120%" height="130%"><feDropShadow dx="0" dy="10" stdDeviation="12" flood-color="#000" flood-opacity="0.35"/></filter></defs>` +
    `<rect x="100" y="100" width="824" height="824" rx="185" fill="${p.bg}" filter="url(#sh)"/>` +
    `<g clip-path="url(#sq)"><svg x="100" y="100" width="824" height="824" viewBox="0 0 ${S} ${S}">${inner}</svg></g></svg>`
  );
})();
const set = 'macos/Brainfence/Resources/Assets.xcassets';
const images = [];
for (const pt of [16, 32, 128, 256, 512]) {
  for (const scale of [1, 2]) {
    const name = `icon_${pt}x${pt}${scale === 2 ? '@2x' : ''}.png`;
    write(`${set}/AppIcon.appiconset/${name}`, png(mac, pt * scale));
    images.push({ filename: name, idiom: 'mac', scale: `${scale}x`, size: `${pt}x${pt}` });
  }
}
const info = { author: 'xcode', version: 1 };
write(`${set}/Contents.json`, JSON.stringify({ info }, null, 2) + '\n');
write(`${set}/AppIcon.appiconset/Contents.json`, JSON.stringify({ images, info }, null, 2) + '\n');

// Google Play: a full-bleed 512px icon (Play rounds the corners) and the
// 1024×500 feature graphic.
write('store/play/icon-512.png', png(svg('icon'), 512));
write('store/play/feature-graphic.png', png(renderFeatureGraphic(mark, p), 1024));

// The website: the mark as drawn, and the home-screen icon iOS asks for.
write('site/icon.svg', renderMark(mark, p, 'icon'));
write('site/apple-touch-icon.png', png(svg('icon'), 180));

console.log(`icons: wrote ${count} files`);

// A .ico holding PNG images, which every Windows version since Vista reads.
function ico(pngs) {
  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(pngs.length, 4);
  const entries = [];
  let offset = 6 + 16 * pngs.length;
  for (const data of pngs) {
    const size = data.readUInt32BE(16);
    const e = Buffer.alloc(16);
    e.writeUInt8(size >= 256 ? 0 : size, 0);
    e.writeUInt8(size >= 256 ? 0 : size, 1);
    e.writeUInt16LE(1, 4);
    e.writeUInt16LE(32, 6);
    e.writeUInt32LE(data.length, 8);
    e.writeUInt32LE(offset, 12);
    offset += data.length;
    entries.push(e);
  }
  return Buffer.concat([header, ...entries, ...pngs]);
}
